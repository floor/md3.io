// The Themes page's built-in themes: each one's colour roles, light and dark, as mtrl's
// compiled theme CSS declares them (tokens.ts reads it), and its tonal palettes, from the
// seed mtrl generates it from or, for a theme set by hand, from its light primary. The
// seed is read from optional structured metadata, then from generate-themes.ts's
// SCSS header. Missing provenance uses CSS primary for fallback palettes; these are the
// engine's (src/shared/theme-engine.ts).
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { root } from './content';
import { themeTokens } from './tokens';
import { themes } from '../shared/button';
import { HEX, THEME_ROLES, VARIANTS, themeColors, type ColorSpec, type CoreColor } from '../shared/theme-engine';

export interface BuiltInTheme {
  name: string;
  label: string;
  /** Role → hex for every THEME_ROLES role, from the theme's CSS. */
  roles: { light: Record<string, string>; dark: Record<string, string> };
  /** What mtrl generates the theme from, when it does. */
  origin?: ColorSpec & { text: string };
  /** A generated theme whose provenance is unavailable. */
  originUnknown?: boolean;
  /**
   * A hand-made or unknown-origin theme's seed for generated variants: its light
   * primary. Its own colours stay "Original"; its palettes are Tonal Spot's from this seed.
   */
  handSeed?: string;
  palettes: Record<CoreColor, string[]>;
}

/** M3's baseline seed: mtrl's baseline is M3's hand-tuned baseline scheme of this seed (generate-themes.ts, BASELINE_SEED). */
const BASELINE: ColorSpec = { source: '#6750a4', variant: 'tonal-spot', contrast: 0 };
const HEADER = /Generated by scripts\/generate-themes\.ts \(([^)]*)\)/;

const HAND_KEPT = new Set(['ocean', 'forest', 'spring', 'sunset', 'autumn']);
const themeDirectory = resolve(root, 'node_modules/material/src/styles/themes');
const record = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value);

/** Validate optional metadata before passing any colour or number to the engine.
 * themes.json is a name-keyed object of source/variant/contrast/core.secondary entries. Generator field names
 * (seed, contrastLevel, secondary) and variant labels are also accepted.
 * This adapter can be replaced when material publishes a stable metadata contract.
 */
export function originFromMetadata(value: unknown): ColorSpec | undefined {
  if (!record(value)) return undefined;
  const source = value.source === undefined ? value.seed : value.source;
  const variant = VARIANTS.find(entry => entry.name === value.variant || entry.label === value.variant)?.name;
  const contrast = value.contrast === undefined ? (value.contrastLevel === undefined ? 0 : value.contrastLevel) : value.contrast;
  if (typeof source !== 'string' || !HEX.test(source) || !variant || typeof contrast !== 'number' || !Number.isFinite(contrast) || contrast < -1 || contrast > 1) return undefined;
  if (value.core !== undefined && !record(value.core)) return undefined;
  // The viewer currently supports the generator's secondary override only.
  if (record(value.core) && Object.keys(value.core).some(key => key !== 'secondary')) return undefined;
  const secondary = (record(value.core) ? value.core.secondary : undefined) ?? value.secondary;
  if (secondary !== undefined && (typeof secondary !== 'string' || !HEX.test(secondary))) return undefined;
  if (value.match !== undefined && value.match !== false) return undefined;
  return {
    source: source.toLowerCase(), variant, contrast,
    ...(typeof secondary === 'string' ? { core: { secondary: secondary.toLowerCase() } } : {}),
  };
}

/** The spec a generated theme's SCSS header records. Invalid optional fields invalidate the spec too. */
export function originOf(header: string): ColorSpec | undefined {
  const fields = Object.fromEntries(header.split(',').map(part => { const [key, ...value] = part.trim().split(/\s+/); return [key, value.join(' ')]; }));
  return originFromMetadata({ ...fields, contrastLevel: fields.contrastLevel === undefined ? 0 : fields.contrastLevel.trim() ? Number(fields.contrastLevel) : NaN });
}

/** Optional provenance must never prevent the Themes page from loading. */
function readOptional(file: string): string | undefined {
  try { return readFileSync(file, 'utf8'); } catch { return undefined; }
}

export function originFor(name: string, directory = themeDirectory): ColorSpec | undefined {
  // These themes' colours are set by hand, even if incidental metadata is present.
  if (HAND_KEPT.has(name)) return undefined;
  try {
    const metadata: unknown = JSON.parse(readOptional(resolve(directory, 'themes.json')) ?? 'null');
    const spec = record(metadata) ? originFromMetadata(metadata[name]) : undefined;
    if (spec) return spec;
  } catch { /* Missing or malformed optional metadata falls back to the SCSS. */ }
  if (name === 'baseline') return BASELINE;
  const header = HEADER.exec(readOptional(resolve(directory, `_${name}.scss`)) ?? '')?.[1];
  return header ? originOf(header) : undefined;
}

const label = (name: string) => (name.charAt(0).toUpperCase() + name.slice(1)).replaceAll('-', ' ');
const describe = (spec: ColorSpec) => [
  `seed ${spec.source}`, VARIANTS.find(entry => entry.name === spec.variant)?.label ?? spec.variant,
  ...(spec.core?.secondary ? [`secondary ${spec.core.secondary}`] : []), ...(spec.contrast ? [`contrast ${spec.contrast}`] : []),
].join(', ');

/** Build a theme with safe palettes even when generated provenance has disappeared. */
export function builtInTheme(name: string, roles: BuiltInTheme['roles'], directory = themeDirectory): BuiltInTheme {
  const origin = originFor(name, directory);
  if (origin) return { name, label: label(name), roles, origin: { ...origin, text: describe(origin) }, palettes: themeColors(origin).palettes };
  const primary = roles.light.primary;
  const handSeed = primary && HEX.test(primary) ? primary : BASELINE.source;
  return {
    name, label: label(name), roles, handSeed,
    ...(!HAND_KEPT.has(name) ? { originUnknown: true } : {}),
    palettes: themeColors({ source: handSeed, variant: 'tonal-spot', contrast: 0 }).palettes,
  };
}

export const builtInThemes: BuiltInTheme[] = themes.map(name => {
  const tokens = themeTokens[name]!;
  const pick = (mode: 'light' | 'dark') => Object.fromEntries(THEME_ROLES.map(role => [role, tokens[mode][role]?.value ?? '']));
  return builtInTheme(name, { light: pick('light'), dark: pick('dark') });
});
