// The Themes page's viewer, server side: every built-in theme with its roles from
// mtrl's CSS, the seed read from generate-themes.ts's SCSS header, and the page.
import { describe, expect, test } from 'bun:test';
import { handleRequest } from '../server';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { Eta } from 'eta';
import { builtInTheme, builtInThemes, originFor, originFromMetadata, originOf } from '../src/server/themes';
import { themeTokens } from '../src/server/tokens';
import { themes } from '../src/shared/button';
import { THEME_ROLES } from '../src/shared/theme-engine';

describe('Themes page', () => {
  test('every built-in theme, every role, as mtrl\'s CSS declares it', () => {
    expect(builtInThemes.map(theme => theme.name)).toEqual([...themes]);
    for (const theme of builtInThemes) for (const mode of ['light', 'dark'] as const) for (const role of THEME_ROLES) {
      expect(theme.roles[mode][role]).toMatch(/^#[0-9a-f]{6}$/);
      expect(theme.roles[mode][role]).toBe(themeTokens[theme.name]![mode][role]!.value);
    }
  });
  test('seeds come from the generated SCSS; hand-kept themes have none', () => {
    expect(originOf('seed #9a7a3e, variant Tonal Spot, secondary #4a87c4')).toEqual({ source: '#9a7a3e', variant: 'tonal-spot', contrast: 0, core: { secondary: '#4a87c4' } });
    expect(originOf('seed #6750A4, variant Tonal Spot, contrastLevel 1.0')).toEqual({ source: '#6750a4', variant: 'tonal-spot', contrast: 1 });
    const byName = Object.fromEntries(builtInThemes.map(theme => [theme.name, theme]));
    for (const name of ['baseline', 'vibrant', 'desert', 'highcontrast']) expect(byName[name]!.palettes?.primary.length).toBe(18);
    for (const name of ['ocean', 'forest', 'spring', 'sunset', 'autumn']) {
      expect(byName[name]!.origin).toBeUndefined();
      // Their variants are generated from their light primary, as are their palettes.
      expect(byName[name]!.handSeed).toBe(byName[name]!.roles.light.primary);
      expect(byName[name]!.palettes.primary.length).toBe(18);
    }
  });
  test('missing, malformed and unreadable optional provenance preserves roles and safe palettes', () => {
    const directory = mkdtempSync(join(tmpdir(), 'md3io-theme-origin-'));
    const roles = builtInThemes.find(theme => theme.name === 'desert')!.roles;
    for (const scss of ['', '// No generator header', '// Generated by scripts/generate-themes.ts (seed nope, variant Tonal Spot)', '// Generated by scripts/generate-themes.ts (seed #9a7a3e, variant Tonal Spot, contrastLevel NaN)', '// Generated by scripts/generate-themes.ts (seed #9a7a3e, variant Tonal Spot, secondary nope)']) {
      writeFileSync(join(directory, '_desert.scss'), scss);
      const theme = builtInTheme('desert', roles, directory);
      expect(theme.origin).toBeUndefined();
      expect(theme.originUnknown).toBe(true);
      expect(theme.roles).toEqual(roles);
      expect(theme.handSeed).toBe(roles.light.primary);
      expect(theme.palettes.primary).toHaveLength(18);
      expect(theme.palettes.primary.every(color => /^#[0-9a-f]{6}$/.test(color))).toBe(true);
    }
    const unknown = builtInTheme('desert', roles, directory);
    const eta = new Eta({ views: resolve(import.meta.dir, '../src/server/shells') });
    const html = eta.render('styles-themes', { themes: [unknown], roles: THEME_ROLES, selected: 'desert', themeBase: {}, mtrlVersion: 'fixture' });
    const data = JSON.parse(/id="themes-data">([^<]*)<\/script>/.exec(html)![1]!);
    expect(data.themes[0].origin).toBe('unknown');
    expect(data.themes[0].spec).toBeNull();
    expect(data.themes[0].handSeed).toBe(roles.light.primary);
    expect(data.themes[0].light).toEqual(THEME_ROLES.map(role => roles.light[role]));
    expect(originFor('missing', directory)).toBeUndefined();
    expect(originFor('desert', join(directory, 'missing'))).toBeUndefined();
    // A non-file path cannot be read either; provenance still stays optional.
    expect(originFor('desert', join(directory, '_desert.scss'))).toBeUndefined();
    expect(builtInTheme('missing', { light: {}, dark: {} }, directory).palettes.primary).toHaveLength(18);
    for (const name of ['ocean', 'forest', 'spring', 'sunset', 'autumn']) {
      const theme = builtInTheme(name, roles, directory);
      expect(theme.origin).toBeUndefined();
      expect(theme.originUnknown).toBeUndefined();
      expect(theme.handSeed).toBe(roles.light.primary);
    }
  });
  test('optional structured metadata takes precedence, with SCSS fallback for invalid metadata', () => {
    const directory = mkdtempSync(join(tmpdir(), 'md3io-theme-metadata-'));
    const header = '// Generated by scripts/generate-themes.ts (seed #9a7a3e, variant Tonal Spot, secondary #4a87c4)';
    writeFileSync(join(directory, '_desert.scss'), header);
    const spec = { source: '#AABBCC', variant: 'vibrant' as const, contrast: 0.5, core: { secondary: '#123ABC' } };
    writeFileSync(join(directory, 'themes.json'), JSON.stringify({ desert: spec, ocean: spec }));
    const normalized = { ...spec, source: '#aabbcc', core: { secondary: '#123abc' } };
    expect(originFor('desert', directory)).toEqual(normalized);
    expect(originFor('ocean', directory)).toBeUndefined();
    expect(originFromMetadata({ seed: '#AABBCC', variant: 'Vibrant', contrastLevel: 0.5, secondary: '#123ABC' })).toEqual(normalized);
    for (const metadata of ['{', 'null', '[]', '{}', JSON.stringify({ desert: { ...spec, contrast: 'high' } }), JSON.stringify({ desert: { ...spec, core: { secondary: 'invalid' } } })]) {
      writeFileSync(join(directory, 'themes.json'), metadata);
      expect(originFor('desert', directory)).toEqual(originOf('seed #9a7a3e, variant Tonal Spot, secondary #4a87c4'));
    }
    for (const fields of ['seed #123456, variant Unknown', 'seed #123456, variant Tonal Spot, contrastLevel Infinity', 'seed #123456, variant Tonal Spot, contrastLevel 2', 'seed #123456, variant Tonal Spot, contrastLevel']) expect(originOf(fields)).toBeUndefined();
    for (const value of [null, [], 'seed', { ...spec, contrast: NaN }, { ...spec, contrast: null }, { ...spec, core: [] }]) expect(originFromMetadata(value)).toBeUndefined();
  });
  test('the page mounts the app with every theme\'s data and the linked one selected', async () => {
    const html = await (await handleRequest(new Request('http://localhost/styles/themes/?theme=summer'))).text();
    const summer = builtInThemes.find(theme => theme.name === 'summer')!;
    const data = JSON.parse(/<script type="application\/json" id="themes-data">([^<]*)<\/script>/.exec(html)![1]!);
    expect(data.selected).toBe('summer');
    expect(data.roles).toEqual([...THEME_ROLES]);
    expect(data.themes.map((theme: { name: string }) => theme.name)).toEqual([...themes]);
    expect(data.themes.find((theme: { name: string }) => theme.name === 'summer').light[THEME_ROLES.indexOf('primary')]).toBe(summer.roles.light.primary);
    expect(html).toContain('<div class="theme-app" id="theme-app"');
    expect(html).toMatch(/src="\/dist\/theme-app\.[a-f0-9]{10}\.js"/);
    expect(html).not.toContain('src="/dist/styles.js');
    expect(html).toContain('id="theme-base"');
    const unknown = await (await handleRequest(new Request('http://localhost/styles/themes/?theme=nope'))).text();
    expect(unknown).toContain('"selected":"baseline"');
  });
});
